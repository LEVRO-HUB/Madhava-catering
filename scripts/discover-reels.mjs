// Regenerates src/data/reels.js from whatever video files actually exist
// in public/assets/reels/. Run this after adding or removing reel videos:
//     node scripts/discover-reels.mjs
// It does not touch the videos themselves — only the generated data file.
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(decodeURIComponent(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1'))), '..');
const reelsDir = path.join(root, 'public', 'assets', 'reels');
const outFile = path.join(root, 'src', 'data', 'reels.js');

const VIDEO_EXTENSIONS = /\.(mp4|mov|webm|m4v)$/i;

function titleFromFilename(filename) {
  const base = filename.replace(VIDEO_EXTENSIONS, '');
  const spaced = base.replace(/[_-]+/g, ' ').replace(/([a-zA-Z])(\d)/g, '$1 $2').trim();
  return `Catering ${spaced}`;
}

function numberFromFilename(filename) {
  const match = filename.match(/(\d+)/);
  return match ? parseInt(match[1], 10) : Number.MAX_SAFE_INTEGER;
}

function run() {
  const files = fs
    .readdirSync(reelsDir)
    .filter((f) => VIDEO_EXTENSIONS.test(f))
    .sort((a, b) => numberFromFilename(a) - numberFromFilename(b));

  if (files.length === 0) {
    console.warn('No video files found in public/assets/reels/ — reels.js not changed.');
    return;
  }

  const entries = files.map((file, i) => ({
    id: `reel-${i + 1}`,
    src: `/assets/reels/${file}`,
    title: titleFromFilename(file),
  }));

  const content = `// AUTO-GENERATED by scripts/discover-reels.mjs — do not hand-edit the
// entries below; re-run that script after adding/removing files in
// public/assets/reels/. Titles are derived from file names; adjust the
// derivation logic in the script, not here, if you want different titles.
export const reels = ${JSON.stringify(entries, null, 2)};
`;

  fs.writeFileSync(outFile, content);
  console.log(`Discovered ${entries.length} reel video(s):`);
  entries.forEach((e) => console.log(`  - ${e.src}`));
}

run();
